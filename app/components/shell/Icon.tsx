export function isIconName(value: string): value is IconName {
  return Object.hasOwn(ICONS, value);
}

/** A line icon. Unknown names (e.g. old emoji category icons) fall back to a tag. */
export default function Icon({
  name,
  className = "h-5 w-5",
  strokeWidth = 2,
}: {
  name: IconName | string;
  className?: string;
  strokeWidth?: number;
}) {
  const Component = isIconName(name) ? ICONS[name] : Tag;
  return <Component aria-hidden="true" className={className} strokeWidth={strokeWidth} />;
}
